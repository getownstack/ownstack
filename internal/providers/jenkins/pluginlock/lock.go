// Package pluginlock resolves and reads the Jenkins plugin lock: the complete
// set of plugins, transitive dependencies included, at exact versions verified
// for one Jenkins core. Every ownstackctl release embeds one lock, so a stack
// installs the same plugins on every run instead of whatever is newest that
// day.
package pluginlock

import (
	"bufio"
	"bytes"
	"fmt"
	"regexp"
	"sort"
	"strings"
)

// Header is the first line of a generated lock.
const Header = "# Generated by lockgen. Do not edit; run: go run ./internal/providers/jenkins/lockgen"

// ImageRepository is the Jenkins controller image the lock is verified with.
const ImageRepository = "jenkins/jenkins"

// ImageTag is the controller image tag for a core: the LTS on JDK 21.
func ImageTag(core string) string { return core + "-jdk21" }

// Entry is one plugin at an exact version.
type Entry struct{ Name, Version string }

func (e Entry) String() string { return e.Name + ":" + e.Version }

// Lock is a parsed plugins.lock.
type Lock struct {
	// Chart is the jenkins/jenkins Helm chart version, Jenkins its appVersion.
	Chart, Jenkins string
	// Image is the controller image, jenkins/jenkins:<Jenkins>-jdk21.
	Image   string
	Plugins []Entry
}

// New returns a lock for chart and core with the image derived from core.
func New(chart, core string, plugins []Entry) *Lock {
	return &Lock{Chart: chart, Jenkins: core, Image: ImageRepository + ":" + ImageTag(core), Plugins: plugins}
}

// ImageTag is the tag part of Image.
func (l *Lock) ImageTag() string {
	_, tag, _ := strings.Cut(l.Image, ":")
	return tag
}

var (
	pluginName    = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_.-]*$`)
	pluginVersion = regexp.MustCompile(`^[A-Za-z0-9_.+-]+$`)
	coreVersion   = regexp.MustCompile(`^[0-9]+\.[0-9]+(\.[0-9]+)?$`)
	chartVersion  = regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+$`)
)

// Format renders the lock: the header, then one name:version line per
// plugin, sorted by name. jenkins-plugin-cli reads it as a plugin file.
func (l *Lock) Format() []byte {
	var b bytes.Buffer
	fmt.Fprintln(&b, Header)
	fmt.Fprintf(&b, "# chart: %s\n# jenkins: %s\n# image: %s\n", l.Chart, l.Jenkins, l.Image)
	for _, e := range l.Plugins {
		fmt.Fprintln(&b, e.String())
	}
	return b.Bytes()
}

// ParseLock reads and checks a lock: the generated header with chart,
// jenkins, and image lines, then unique name:version lines sorted by name.
func ParseLock(data []byte) (*Lock, error) {
	lines := strings.Split(strings.TrimRight(string(data), "\n"), "\n")
	if len(lines) < 4 || lines[0] != Header {
		return nil, fmt.Errorf("plugins.lock: missing the generated header")
	}
	l := &Lock{}
	for i, field := range []struct {
		key string
		dst *string
	}{{"chart", &l.Chart}, {"jenkins", &l.Jenkins}, {"image", &l.Image}} {
		v, ok := strings.CutPrefix(lines[i+1], "# "+field.key+": ")
		if !ok || v == "" {
			return nil, fmt.Errorf("plugins.lock line %d: want %q", i+2, "# "+field.key+": <value>")
		}
		*field.dst = v
	}
	if !chartVersion.MatchString(l.Chart) {
		return nil, fmt.Errorf("plugins.lock: chart %q is not a chart version", l.Chart)
	}
	if !coreVersion.MatchString(l.Jenkins) {
		return nil, fmt.Errorf("plugins.lock: jenkins %q is not a core version", l.Jenkins)
	}
	if want := ImageRepository + ":" + ImageTag(l.Jenkins); l.Image != want {
		return nil, fmt.Errorf("plugins.lock: image %q, want %q", l.Image, want)
	}
	for i, line := range lines[4:] {
		e, err := parseEntry(line)
		if err != nil {
			return nil, fmt.Errorf("plugins.lock line %d: %w", i+5, err)
		}
		if n := len(l.Plugins); n > 0 && l.Plugins[n-1].Name >= e.Name {
			return nil, fmt.Errorf("plugins.lock line %d: %s is not sorted or repeats", i+5, e.Name)
		}
		l.Plugins = append(l.Plugins, e)
	}
	if len(l.Plugins) == 0 {
		return nil, fmt.Errorf("plugins.lock: no plugins")
	}
	return l, nil
}

func parseEntry(s string) (Entry, error) {
	name, version, ok := strings.Cut(s, ":")
	if !ok || !pluginName.MatchString(name) || !pluginVersion.MatchString(version) {
		return Entry{}, fmt.Errorf("%q is not name:version", s)
	}
	return Entry{name, version}, nil
}

// ParseInput reads plugins.in: one plugin name per line; blank lines and
// '#' comments (whole-line or trailing) are ignored.
func ParseInput(data []byte) ([]string, error) {
	var names []string
	seen := map[string]bool{}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for n := 1; sc.Scan(); n++ {
		line, _, _ := strings.Cut(sc.Text(), "#")
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		if !pluginName.MatchString(line) {
			return nil, fmt.Errorf("plugins.in line %d: %q is not a plugin name (versions belong in the lock)", n, line)
		}
		if seen[line] {
			return nil, fmt.Errorf("plugins.in line %d: %s is listed twice", n, line)
		}
		seen[line] = true
		names = append(names, line)
	}
	if len(names) == 0 {
		return nil, fmt.Errorf("plugins.in lists no plugins")
	}
	return names, sc.Err()
}

// ParseExtra reads the extraPlugins setting: space-separated name:version
// pairs. A later pair for the same plugin replaces an earlier one.
func ParseExtra(s string) ([]Entry, error) {
	var out []Entry
	index := map[string]int{}
	for _, field := range strings.Fields(s) {
		e, err := parseEntry(field)
		if err != nil {
			return nil, err
		}
		if i, ok := index[e.Name]; ok {
			out[i] = e
			continue
		}
		index[e.Name] = len(out)
		out = append(out, e)
	}
	return out, nil
}

// Changes lists how next differs from prev (which may be nil): the chart and
// core, then plugins added, upgraded or downgraded, and removed, by name.
func Changes(prev, next *Lock) []string {
	if prev == nil {
		prev = &Lock{}
	}
	var out []string
	if prev.Chart != next.Chart {
		out = append(out, fmt.Sprintf("chart %s → %s", orNone(prev.Chart), next.Chart))
	}
	if prev.Jenkins != next.Jenkins {
		out = append(out, fmt.Sprintf("Jenkins %s → %s", orNone(prev.Jenkins), next.Jenkins))
	}
	old := map[string]string{}
	for _, e := range prev.Plugins {
		old[e.Name] = e.Version
	}
	var removed []string
	for _, e := range next.Plugins {
		v, ok := old[e.Name]
		delete(old, e.Name)
		switch {
		case !ok:
			out = append(out, fmt.Sprintf("added %s %s", e.Name, e.Version))
		case Compare(e.Version, v) > 0:
			out = append(out, fmt.Sprintf("upgraded %s %s → %s", e.Name, v, e.Version))
		case v != e.Version:
			out = append(out, fmt.Sprintf("downgraded %s %s → %s", e.Name, v, e.Version))
		}
	}
	for name, v := range old {
		removed = append(removed, fmt.Sprintf("removed %s %s", name, v))
	}
	sort.Strings(removed)
	return append(out, removed...)
}

func orNone(s string) string {
	if s == "" {
		return "(none)"
	}
	return s
}

// With returns the lock's plugins plus extra, sorted by name. An extra plugin
// that is already locked replaces the locked version.
func (l *Lock) With(extra []Entry) []Entry {
	merged := map[string]string{}
	for _, e := range l.Plugins {
		merged[e.Name] = e.Version
	}
	for _, e := range extra {
		merged[e.Name] = e.Version
	}
	out := make([]Entry, 0, len(merged))
	for name, version := range merged {
		out = append(out, Entry{name, version})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}
